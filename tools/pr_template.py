from __future__ import annotations

from graph.state import IssueContext, PatchOutput, PlanningOutput, ValidationOutput


def build_pr_title(ctx: IssueContext) -> str:
    return f"fix: auto-repair for issue #{ctx.issue_number} — {ctx.title}"


def build_pr_body(
    ctx: IssueContext,
    planning: PlanningOutput,
    patch: PatchOutput,
    validation: ValidationOutput,
) -> str:
    return f"""## Automated Fix for #{ctx.issue_number}

**Issue:** {ctx.title}

### Fix Strategy
{planning.fix_strategy}

### Changes Made
{patch.explanation}

### Validation Results
- Tests: {'Passed' if validation.tests_passed else 'Failed'} (exit {validation.test_exit_code})
- Lint: {'Passed' if validation.lint_passed else 'Failed'}
- Type Check: {'Passed' if validation.type_check_passed else 'Failed'}

### Files Modified
{chr(10).join(f'- `{fc.path}` — {fc.description}' for fc in patch.file_changes)}

---
*This PR was generated by the multi-agent code repair system. Please review before merging.*

Closes #{ctx.issue_number}
"""
